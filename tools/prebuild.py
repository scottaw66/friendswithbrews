#!/opt/homebrew/bin/python3
"""Build step 1: refresh the generated artifacts the Zola templates need.

content/ (TOML-frontmatter markdown) and data/ (JSON) are the ONE authoring
tree — edit them directly; the episode pipeline in
~/Developer/Sites/website-scripts/fwb/ writes them too. There is no converter
and no second copy (the YAML src/content + src/data tree and
migrate/convert.py were retired 2026-11-06; see ZOLA-MIGRATION.md).

This script owns ONLY generated artifacts and never rewrites a hand-authored
body. It is idempotent: a second run right after the first writes nothing.
Run from any cwd; exit 1 on any error (which fails the build).

What it refreshes:

  1. Derived display fields in each page's [extra] table, edited in place
     (only those `key = …` lines change): episodes (content/<n>.md) get
     duration, display_date, rfc2822_date and has_transcript; transcripts
     (content/transcripts/<n>.md) get display_date. Templates use these
     because Tera v2's date filter can't parse ISO 8601 datetimes and its
     formatting differs from the date-fns output the site always had.
  2. content/listpages/*.md — pagination stubs for /episodes/N, /brews/N and
     /transcripts/page/N, counted from content/, data/brews.json and
     content/transcripts/; stale stubs are deleted.
  3. content/bottle/<id>.md — one stub per brew in data/brews.json with the
     brew embedded in [extra] (plus the episode-number→title map and the
     precomputed url_hostname/url_origin, since Tera can't parse URLs);
     stale stubs are deleted.

What it validates (the old Astro Zod schemas, then convert.py's lint):
frontmatter keys and required fields, slug/episode vs filename, date and
length formats, brews.json ids/types/votes/episode references and that every
brew image exists in src/assets/images/brews/. It also fails the build on:
  - YAML `---` frontmatter (a pre-2026-11-06 src/ file pasted in),
  - a literal {{ / {% / {# in a body outside {% raw %}…{% endraw %} and
    outside a {{<component />}} call (Zola renders content as Tera),
  - Astro-era `../../assets/images/` image syntax (use {{<content_image />}}).

Zero dependencies on purpose: TOML is read with the stdlib tomllib and
written by editing single lines, so everything else in a file is preserved
byte for byte.
"""

import json
import math
import re
import sys
import tomllib
from datetime import date as date_type, datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo

REPO = Path(__file__).resolve().parent.parent
CONTENT = REPO / "content"
TRANSCRIPTS = CONTENT / "transcripts"
LISTPAGES = CONTENT / "listpages"
BOTTLE = CONTENT / "bottle"
DATA = REPO / "data"
BREW_IMAGES = REPO / "src/assets/images/brews"

# Pagination sizes — must match [extra] in zola.toml (templates slice with
# the same values; the stub count is baked here).
EPISODES_PER_PAGE = 5
TRANSCRIPTS_PER_PAGE = 20
BREWS_PER_PAGE = 12

LA = ZoneInfo("America/Los_Angeles")

# English day/month names hardcoded instead of strftime %A/%b so output can
# never depend on the running locale (parity with date-fns enUS).
DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"]
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
          "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

GENERATED = "# GENERATED by tools/prebuild.py — do not edit; regenerated on every build"

errors: list[str] = []
warnings: list[str] = []
stats = {"written": 0, "unchanged": 0, "pruned": 0}


def err(msg: str) -> None:
    errors.append(msg)


def warn(msg: str) -> None:
    warnings.append(msg)


def rel(path: Path) -> str:
    return str(path.relative_to(REPO))


# --------------------------------------------------------------------------
# Output helpers
# --------------------------------------------------------------------------

def tstr(s: str) -> str:
    """TOML basic string. JSON string syntax is a subset of TOML's escaping
    (json.dumps never emits the \\/ escape and escapes all control chars)."""
    return json.dumps(str(s), ensure_ascii=False)


def tval(v) -> str:
    """TOML value for the derived fields: bool, int or basic string."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return tstr(v)


def write_if_changed(path: Path, content: str) -> None:
    """Skip byte-identical writes — mass rewrites fire hundreds of file
    events and wedge `zola serve` (learned on scottwillsey, commit 0efc5a5).
    This is also what lets dev.sh re-run this script on every content/ or
    data/ change without looping: the run triggered by our own writes
    writes nothing."""
    if path.exists() and path.read_text(encoding="utf-8") == content:
        stats["unchanged"] += 1
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    stats["written"] += 1
    print(f"wrote {rel(path)}")


def prune_stale(directory: Path, pattern: str, keep: set[str]) -> None:
    """Delete generated stubs that no longer correspond to anything."""
    for path in directory.glob(pattern):
        if path.name in keep or path.name == "_index.md":
            continue
        path.unlink()
        stats["pruned"] += 1
        print(f"pruned stale {rel(path)}")


# --------------------------------------------------------------------------
# Frontmatter: split, parse (tomllib), edit single lines in [extra]
# --------------------------------------------------------------------------

FRONTMATTER_RE = re.compile(r"^\+\+\+\n(.*?)\n\+\+\+\n?(.*)\Z", re.S)
TABLE_HEADER_RE = re.compile(r"^\s*\[")
KEY_LINE_RE = re.compile(r"^([A-Za-z0-9_-]+)\s*=")


def split_frontmatter(text: str, path: Path) -> tuple[str, str, dict] | None:
    """Return (frontmatter text, body, parsed frontmatter) or None on error.
    The body is everything after the closing +++ line, kept verbatim."""
    if text.startswith("---\n"):
        err(f"{rel(path)}: YAML frontmatter — this is the pre-2026-11-06 "
            f"src/ form; the site reads TOML (+++) now")
        return None
    m = FRONTMATTER_RE.match(text)
    if not m:
        err(f"{rel(path)}: no +++ frontmatter block")
        return None
    fm_text, body = m.groups()
    try:
        fm = tomllib.loads(fm_text)
    except tomllib.TOMLDecodeError as e:
        err(f"{rel(path)}: frontmatter is not valid TOML: {e}")
        return None
    return fm_text, body, fm


def set_extra_fields(fm_text: str, fm: dict, wanted: dict, path: Path) -> str:
    """Return fm_text with each wanted key = value present in the [extra]
    table, editing only those lines: an existing `key = …` line is replaced,
    a missing key is appended at the end of the table, and a missing [extra]
    table is created at the end of the frontmatter. Returns fm_text unchanged
    when every value already matches.

    Layout assumption (true for every episode and transcript, which the
    pipeline writes and convert.py used to): [extra] is a plain table whose
    entries each START on their own `key = …` line (description_rss is one
    long line). The edited text is re-parsed and the wanted values re-read
    before it is accepted, so a layout this can't handle fails loudly
    instead of corrupting a file."""
    extra = fm.get("extra", {})
    if all(extra.get(k) == v for k, v in wanted.items()):
        return fm_text
    lines = fm_text.split("\n")
    try:
        start = next(i for i, l in enumerate(lines) if l.strip() == "[extra]") + 1
    except StopIteration:
        lines += ["", "[extra]"]
        start = len(lines)
    end = start
    while end < len(lines) and not TABLE_HEADER_RE.match(lines[end]):
        end += 1
    key_lines = {m.group(1): i for i in range(start, end)
                 if (m := KEY_LINE_RE.match(lines[i]))}
    if set(key_lines) != set(extra):
        err(f"{rel(path)}: [extra] has entries this script can't edit "
            f"line-by-line (multi-line or dotted keys?) — fix by hand")
        return fm_text
    for k, v in wanted.items():
        if extra.get(k) == v:
            continue
        new_line = f"{k} = {tval(v)}"
        if k in key_lines:
            lines[key_lines[k]] = new_line
        else:
            # Insert before any blank lines that end the table so the entry
            # stays inside it.
            at = end
            while at > start and not lines[at - 1].strip():
                at -= 1
            lines.insert(at, new_line)
            end += 1
            for kk in key_lines:
                if key_lines[kk] >= at:
                    key_lines[kk] += 1
            key_lines[k] = at
    new_text = "\n".join(lines)
    try:
        check = tomllib.loads(new_text)
    except tomllib.TOMLDecodeError as e:  # should be unreachable
        err(f"{rel(path)}: edited frontmatter is not valid TOML: {e}")
        return fm_text
    if any(check.get("extra", {}).get(k) != v for k, v in wanted.items()):
        err(f"{rel(path)}: [extra] edit did not take — fix by hand")
        return fm_text
    return new_text


# --------------------------------------------------------------------------
# Validation (the old Astro Zod schemas, as convert.py carried them)
# --------------------------------------------------------------------------

LENGTH_RE = re.compile(r"^\d{2}:\d{2}:\d{2}$")
YOUTUBE_RE = re.compile(r"^[A-Za-z0-9_-]{11}$")

TOP_KEYS = {"title", "description", "date", "slug", "extra"}
TOP_REQUIRED = {"title", "description", "date", "slug"}
# Source fields the pipeline writes, plus the derived ones this script owns.
EPISODE_DERIVED = {"duration", "display_date", "rfc2822_date", "has_transcript"}
EPISODE_EXTRA = {"episode", "audio_file", "length", "bytes", "youtube",
                 "description_rss"} | EPISODE_DERIVED
EPISODE_EXTRA_REQUIRED = {"episode", "audio_file", "length", "bytes"}
# Transcripts: episode fields minus description_rss; bytes optional (the old
# Zod schema); display_date is the only derived field.
TRANSCRIPT_DERIVED = {"display_date"}
TRANSCRIPT_EXTRA = {"episode", "audio_file", "length", "bytes", "youtube"} | TRANSCRIPT_DERIVED
TRANSCRIPT_EXTRA_REQUIRED = {"episode", "audio_file", "length"}


def page_date(fm: dict, path: Path) -> datetime | None:
    """The TOML `date` as an aware datetime. tomllib already parses an
    offset datetime (`date = 2026-11-06T00:10:00-08:00`, the only form in
    this tree); a quoted string, a bare date or a naive datetime is an error
    so a typo can't silently shift the feed's pubDate."""
    d = fm.get("date")
    if isinstance(d, datetime) and d.tzinfo is not None:
        return d
    if isinstance(d, datetime):
        err(f"{rel(path)}: date has no UTC offset — use YYYY-MM-DDTHH:MM:SS-08:00")
    elif isinstance(d, date_type):
        err(f"{rel(path)}: date has no time — use YYYY-MM-DDTHH:MM:SS-08:00")
    elif d is None:
        err(f"{rel(path)}: missing date")
    else:
        err(f"{rel(path)}: date must be a bare TOML datetime, not {d!r}")
    return None


def validate_page(path: Path, fm: dict, extra_known: set, extra_required: set) -> bool:
    ok = True
    for key in fm:
        if key not in TOP_KEYS:
            err(f"{rel(path)}: unknown frontmatter key {key!r}")
            ok = False
    for key in TOP_REQUIRED:
        if key not in fm or (isinstance(fm[key], str) and not fm[key].strip()):
            err(f"{rel(path)}: missing required key {key!r}")
            ok = False
    extra = fm.get("extra")
    if not isinstance(extra, dict):
        err(f"{rel(path)}: missing [extra] table")
        return False
    for key in extra:
        if key not in extra_known:
            err(f"{rel(path)}: unknown [extra] key {key!r}")
            ok = False
    for key in extra_required:
        if key not in extra or (isinstance(extra[key], str) and not extra[key].strip()):
            err(f"{rel(path)}: missing required [extra] key {key!r}")
            ok = False
    if not ok:
        return False
    stem = path.stem
    if str(fm["slug"]) != stem:
        err(f"{rel(path)}: slug {fm['slug']!r} does not match filename")
        ok = False
    if str(extra["episode"]) != stem:
        err(f"{rel(path)}: episode {extra['episode']!r} does not match filename")
        ok = False
    if not LENGTH_RE.match(str(extra["length"])):
        err(f"{rel(path)}: length {extra['length']!r} is not HH:MM:SS")
        ok = False
    if "bytes" in extra and not str(extra["bytes"]).isdigit():
        err(f"{rel(path)}: bytes {extra['bytes']!r} is not numeric")
        ok = False
    if extra.get("youtube") and not YOUTUBE_RE.match(str(extra["youtube"])):
        err(f"{rel(path)}: youtube {extra['youtube']!r} is not an 11-char video id")
        ok = False
    return ok


# --------------------------------------------------------------------------
# Body checks (never rewritten — only validated)
# --------------------------------------------------------------------------

RAW_SPAN_RE = re.compile(r"{% raw %}.*?{% endraw %}", re.S)
COMPONENT_RE = re.compile(r"{{<[^\n]*?/>}}")
TERA_TOKEN_RE = re.compile(r"{{|{%|{#")
# Astro-era body image syntax (anything under the old src/assets/images
# root). convert.py used to rewrite these into {{<content_image />}} calls;
# now they mean someone pasted old-style markdown.
ASSET_IMG_RE = re.compile(r"\]\(\s*(?:\.\./)*assets/images/")


def check_body(body: str, path: Path) -> None:
    if ASSET_IMG_RE.search(body):
        err(f"{rel(path)}: Astro-era ../../assets/images/ image syntax in the "
            f"body — use {{{{<content_image path={{\"…\"}} alt={{\"…\"}} />}}}}")
    stripped = COMPONENT_RE.sub("", RAW_SPAN_RE.sub("", body))
    m = TERA_TOKEN_RE.search(stripped)
    if m:
        line = stripped.count("\n", 0, m.start()) + 1
        err(f"{rel(path)}: literal {m.group()!r} near body line {line} — Zola "
            f"renders content as Tera; wrap the line in {{% raw %}}…{{% endraw %}}")


# --------------------------------------------------------------------------
# Derived fields (ports of the frozen Astro utilities DateFormat.mjs and
# episodelength.mjs, carried over from convert.py)
# --------------------------------------------------------------------------

def rfc2822_date(dt: datetime) -> str:
    """UTC-rendered RFC-1123, byte-matching @astrojs/rss (JS toUTCString)."""
    u = dt.astimezone(timezone.utc)
    return (f"{DAYS[u.weekday()][:3]}, {u.day:02d} {MONTHS[u.month - 1]} "
            f"{u.year} {u.hour:02d}:{u.minute:02d}:{u.second:02d} GMT")


def display_date(dt: datetime) -> str:
    """date-fns 'eeee, dd MMM yyyy' in America/Los_Angeles (build-machine TZ
    under Astro; pinned here so builds are location-independent)."""
    l = dt.astimezone(LA)
    return f"{DAYS[l.weekday()]}, {l.day:02d} {MONTHS[l.month - 1]} {l.year}"


def episode_length(length: str) -> str:
    """Line-by-line port of episodelength.mjs episodeLength()."""
    hours, minutes = length.split(":")[0], length.split(":")[1]
    display = ""
    if int(hours) > 0:
        display = hours + " hour" + ("s" if int(hours) > 1 else "") + " "
    display += minutes + " minutes"
    return re.sub(r"^0", "", display, count=1)


# --------------------------------------------------------------------------
# Episodes (content/<n>.md) and transcripts (content/transcripts/<n>.md)
# --------------------------------------------------------------------------

def numbered_pages(directory: Path) -> list[Path]:
    return sorted((p for p in directory.glob("[0-9]*.md")), key=lambda p: int(p.stem))


def refresh_episodes(transcript_stems: set[str]) -> dict[str, str]:
    """Validate every episode page, refresh its derived [extra] fields in
    place, and return {episode number: title} for the bottle stubs."""
    titles: dict[str, str] = {}
    for path in numbered_pages(CONTENT):
        text = path.read_text(encoding="utf-8")
        parsed = split_frontmatter(text, path)
        if parsed is None:
            continue
        fm_text, body, fm = parsed
        if not validate_page(path, fm, EPISODE_EXTRA, EPISODE_EXTRA_REQUIRED):
            continue
        dt = page_date(fm, path)
        if dt is None:
            continue
        check_body(body, path)
        titles[path.stem] = str(fm["title"])
        wanted = {
            "duration": episode_length(str(fm["extra"]["length"])),
            "display_date": display_date(dt),
            "rfc2822_date": rfc2822_date(dt),
            "has_transcript": path.stem in transcript_stems,
        }
        new_fm = set_extra_fields(fm_text, fm, wanted, path)
        write_if_changed(path, "+++\n" + new_fm + "\n+++\n" + body)
    return titles


def refresh_transcripts() -> set[str]:
    stems: set[str] = set()
    for path in numbered_pages(TRANSCRIPTS):
        text = path.read_text(encoding="utf-8")
        parsed = split_frontmatter(text, path)
        if parsed is None:
            continue
        fm_text, body, fm = parsed
        if not validate_page(path, fm, TRANSCRIPT_EXTRA, TRANSCRIPT_EXTRA_REQUIRED):
            continue
        dt = page_date(fm, path)
        if dt is None:
            continue
        check_body(body, path)
        stems.add(path.stem)
        new_fm = set_extra_fields(fm_text, fm, {"display_date": display_date(dt)}, path)
        write_if_changed(path, "+++\n" + new_fm + "\n+++\n" + body)
    return stems


# --------------------------------------------------------------------------
# Pagination stubs → content/listpages/*.md
#
# Zola's paginator can't express these URL shapes with content that lives
# elsewhere, so each list page is a stub with a `path` override; the
# template slices the real data itself (scottwillsey pattern).
# --------------------------------------------------------------------------

def write_list_stubs(episode_count: int, transcript_count: int,
                     brew_count: int) -> None:
    generated: set[str] = set()

    def stub(filename: str, title: str, url_path: str, template: str,
             page_num: int, aliases: list[str] | None = None) -> None:
        fm = [
            "+++",
            GENERATED,
            f"title = {tstr(title)}",
            f'path = "{url_path}"',
            f'template = "{template}"',
        ]
        if aliases:
            fm.append(f"aliases = {json.dumps(aliases)}")
        fm += ["", "[extra]", f"page_num = {page_num}", "+++", ""]
        write_if_changed(LISTPAGES / filename, "\n".join(fm))
        generated.add(filename)

    for k in range(1, math.ceil(episode_count / EPISODES_PER_PAGE) + 1):
        stub(f"episodes-{k}.md", f"Episodes page {k}", f"episodes/{k}",
             "episodelist.html", k)
    for k in range(1, math.ceil(brew_count / BREWS_PER_PAGE) + 1):
        stub(f"brews-{k}.md", f"Brews page {k}", f"brews/{k}",
             "brewlist.html", k)
    for k in range(1, math.ceil(transcript_count / TRANSCRIPTS_PER_PAGE) + 1):
        # Page 1 also owns /transcripts/ (the old Astro config redirect).
        stub(f"transcripts-{k}.md", f"Transcripts page {k}",
             f"transcripts/page/{k}", "transcriptlist.html", k,
             aliases=["/transcripts"] if k == 1 else None)

    prune_stale(LISTPAGES, "*.md", generated)


# --------------------------------------------------------------------------
# Brews → content/bottle/<id>.md stubs (from data/brews.json)
# --------------------------------------------------------------------------

VALID_BREW_TYPES = {"beer", "coffee", "tea", "water"}
VALID_VOTES = {"thumbs-up", "thumbs-down", "side-thumb"}


def _url_hostname(url: str) -> str:
    """new URL(url).hostname: lowercased host, no port."""
    try:
        return (urlsplit(str(url)).hostname or "").lower()
    except ValueError:
        return ""


def _url_origin(url: str) -> str:
    """new URL(url).origin: scheme://host, keeping only an explicit port.

    (JS drops the scheme's default port; brews.json URLs never carry one, so
    an explicit port passing through verbatim is close enough.)"""
    try:
        parts = urlsplit(str(url))
    except ValueError:
        return ""
    host = (parts.hostname or "").lower()
    if not parts.scheme or not host:
        return ""
    port = f":{parts.port}" if parts.port else ""
    return f"{parts.scheme}://{host}{port}"


def write_bottle_stubs(episode_titles: dict[str, str]) -> int:
    src = DATA / "brews.json"
    try:
        brews = json.loads(src.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        err(f"{rel(src)}: {e}")
        return 0
    if not isinstance(brews, list):
        err(f"{rel(src)}: not a JSON array")
        return 0

    generated: set[str] = set()
    for i, brew in enumerate(brews):
        name = f"brews.json[{i}]"
        bid = str(brew.get("id", ""))
        if not re.fullmatch(r"[A-Za-z0-9_-]+", bid):
            err(f"{name}: bad or missing id {bid!r}")
            continue
        if brew.get("type") not in VALID_BREW_TYPES:
            err(f"{name} ({bid}): bad type {brew.get('type')!r}")
        for field in ("name", "brewery", "image", "url"):
            if not str(brew.get(field, "")).strip():
                err(f"{name} ({bid}): missing {field!r}")
        # Empty description exists in real data (Mud Season) and the old
        # site rendered it as an empty quote — tolerate with a warning.
        if not str(brew.get("description", "")).strip():
            warn(f"{name} ({bid}): empty description")
        image = BREW_IMAGES / f"{brew.get('image')}.png"
        if not image.exists():
            err(f"{name} ({bid}): image not found: {rel(image)}")

        fm = [
            "+++",
            GENERATED,
            f"title = {tstr(brew.get('name', ''))}",
            f'path = "bottle/{bid}"',
            'template = "bottle.html"',
            "",
            "[extra]",
            f"brewery = {tstr(brew.get('brewery', ''))}",
            f"image = {tstr(brew.get('image', ''))}",
            f"brew_description = {tstr(brew.get('description', ''))}",
            f"brew_type = {tstr(brew.get('type', ''))}",
            f"url = {tstr(brew.get('url', ''))}",
            # bottle.html's "<name> on <hostname>" line — Tera can't parse
            # URLs, so mirror JS's new URL(url).hostname/.origin here.
            f"url_hostname = {tstr(_url_hostname(brew.get('url', '')))}",
            f"url_origin = {tstr(_url_origin(brew.get('url', '')))}",
            f"episodes = {json.dumps([str(e) for e in brew.get('episodes', [])])}",
            "",
            "[extra.episode_titles]",
        ]
        for ep in brew.get("episodes", []):
            title = episode_titles.get(str(ep))
            if title is None:
                err(f"{name} ({bid}): references unknown episode {ep!r}")
                title = str(ep)
            fm.append(f"{tstr(ep)} = {tstr(title)}")
        for r in brew.get("rating", []):
            if r.get("vote") not in VALID_VOTES:
                err(f"{name} ({bid}): bad vote {r.get('vote')!r}")
            fm += [
                "",
                "[[extra.rating]]",
                f"host = {tstr(r.get('host', ''))}",
                f"vote = {tstr(r.get('vote', ''))}",
                f"description = {tstr(r.get('description', ''))}",
            ]
        fm += ["+++", ""]
        write_if_changed(BOTTLE / f"{bid}.md", "\n".join(fm))
        generated.add(f"{bid}.md")

    prune_stale(BOTTLE, "*.md", generated)
    return len(brews)


# --------------------------------------------------------------------------

def main() -> int:
    transcript_stems = refresh_transcripts()
    episode_titles = refresh_episodes(transcript_stems)
    brew_count = write_bottle_stubs(episode_titles)
    write_list_stubs(len(episode_titles), len(transcript_stems), brew_count)

    for w in warnings:
        print(f"WARN: {w}")
    if errors:
        for e in errors:
            print(f"ERROR: {e}", file=sys.stderr)
        print(f"\nprebuild.py: {len(errors)} error(s) — failing the build.",
              file=sys.stderr)
        return 1
    print(f"prebuild.py: {len(episode_titles)} episodes, "
          f"{len(transcript_stems)} transcripts, {brew_count} brews | "
          f"{stats['written']} written, {stats['unchanged']} unchanged, "
          f"{stats['pruned']} pruned")
    return 0


if __name__ == "__main__":
    sys.exit(main())
